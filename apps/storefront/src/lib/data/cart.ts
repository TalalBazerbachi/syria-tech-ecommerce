/**
 * Replaces the cart's promo codes. Resolves to the codes Medusa actually
 * applied (an unknown code is rejected with a 400 and throws; a known but
 * inapplicable one is silently dropped from this list).
 */
export async function applyPromotions(codes: string[]): Promise<string[]> {
  const cartId = await getCartId()

  if (!cartId) {
    throw new Error("No existing cart found")
  }

  const headers = {
    ...(await getAuthHeaders()),
  }

  return sdk.store.cart
    .update(cartId, { promo_codes: codes }, {}, headers)
    .then(async ({ cart }: { cart: HttpTypes.StoreCart }) => {
      const cartCacheTag = await getCacheTag("carts")
      revalidateTag(cartCacheTag)

      const fulfillmentCacheTag = await getCacheTag("fulfillment")
      revalidateTag(fulfillmentCacheTag)

      return (cart.promotions ?? [])
        .map((promotion) => promotion.code)
        .filter((code): code is string => typeof code === "string")
    })
    .catch(medusaError)
}

export async function submitPromotionForm(
  currentState: unknown,
  formData: FormData
) {
  const code = formData.get("code") as string
  try {
    await applyPromotions([code])
  } catch (e: unknown) {
    return e instanceof Error ? e.message : String(e)
  }
}

/**
 * Checkout step 1. The single Syrian address form fills both shipping and
 * billing (cash on delivery has no separate billing address).
 */
export async function setAddresses(currentState: unknown, formData: FormData) {
  const t = await getTranslations("address.errors")

  try {
    if (!formData) {
      throw new Error("No form data found when setting addresses")
    }
    const cartId = await getCartId()
    if (!cartId) {
      throw new Error("No existing cart found when setting addresses")
    }

    const parsed = parseAddressForm(formData, "shipping_address.")
    if (!parsed.ok) {
      return t(parsed.error.code)
    }

    // Email is optional (the phone is the contact for cash on delivery). An empty
    // field is left out: Medusa rejects "" and an order needs no email.
    const email = String(formData.get("email") ?? "").trim()

    await updateCart({
      shipping_address: parsed.address,
      billing_address: parsed.address,
      ...(email ? { email } : {}),
    })
  } catch (e: unknown) {
    return e instanceof Error ? e.message : String(e)
  }

  const locale = await getAppLocale()
  redirect(`/${locale}/checkout?step=delivery`)
}

/**
 * Places an order for a cart. If no cart ID is provided, it will use the cart ID from the cookies.
 */
export async function placeOrder(cartId?: string) {
  const id = cartId || (await getCartId())

  if (!id) {
    throw new Error("No existing cart found when placing an order")
  }

  const headers = {
    ...(await getAuthHeaders()),
  }

  const cartRes = await sdk.store.cart
    .complete(id, {}, headers)
    .then(async (cartRes) => {
      const cartCacheTag = await getCacheTag("carts")
      revalidateTag(cartCacheTag)
      return cartRes
    })
    .catch(medusaError)

  if (cartRes?.type === "order") {
    const orderCacheTag = await getCacheTag("orders")
    revalidateTag(orderCacheTag)

    await removeCartId()
    const locale = await getAppLocale()
    redirect(`/${locale}/order/${cartRes?.order.id}/confirmed`)
  }

  return cartRes.cart
}

export async function listCartOptions() {
  const cartId = await getCartId()
  const headers = {
    ...(await getAuthHeaders()),
  }
  const next = {
    ...(await getCacheOptions("shippingOptions")),
  }

  return await sdk.client.fetch<{
    shipping_options: HttpTypes.StoreCartShippingOption[]
  }>("/store/shipping-options", {
    query: { cart_id: cartId },
    next,
    headers,
    cache: "force-cache",
  })
}
